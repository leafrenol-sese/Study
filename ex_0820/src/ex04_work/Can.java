package ex04_work;

public class Can {
    //자판기 속의 캔

   private String name;
   private int price; //여기까지 내가 입력,
   
   //아래는 자동완성 Source action, get과 set을 만들어준다
   public String getName() {
    return name;
   }
   public void setName(String name) {
    this.name = name;
   }
   public int getPrice() {
    return price;
   }
   public void setPrice(int price) {
    this.price = price;
   }
   
   


}
